#!/usr/bin/env node
/**
 * First-run installer. Creates config/business.json and .env for a new client,
 * so a buyer never edits code or a large JSON file by hand.
 *
 *   npm run setup                                  interactive
 *   npm run setup -- --yes --name="Glow Salon" --timezone=Europe/London \
 *       --services="Cut and finish:45:45,Colour consultation:30:0" \
 *       --staff-user=staff --staff-password=secret
 *
 * Flags: --dir, --name, --industry, --timezone, --currency, --location,
 *        --phone, --email, --services, --staff-user, --staff-password,
 *        --ai-provider, --ai-key, --resend-key, --email-from,
 *        --twilio-sid, --twilio-token, --twilio-from,
 *        --bridge-url, --embed-origins, --force, --yes
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import readline from 'node:readline/promises';
import { stdin as input, stdout as output } from 'node:process';

const args = process.argv.slice(2);
const flags = new Map();
for (const arg of args) {
  if (!arg.startsWith('--')) continue;
  const [key, ...rest] = arg.slice(2).split('=');
  flags.set(key, rest.length ? rest.join('=') : 'true');
}

const interactive = !flags.has('yes') && input.isTTY;
const baseDir = path.resolve(flags.get('dir') || process.cwd());
const configPath = path.join(baseDir, 'config', 'business.json');
const envPath = path.join(baseDir, '.env');

const rl = interactive ? readline.createInterface({ input, output }) : null;

async function ask(label, fallback) {
  if (!interactive) return fallback;
  const answer = (await rl.question(`${label}${fallback ? ` [${fallback}]` : ''}: `)).trim();
  return answer || fallback;
}

function slugify(value) {
  return String(value)
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 40) || 'business';
}

function initials(value) {
  const letters = String(value)
    .split(/\s+/)
    .filter((word) => /^[A-Za-z]/.test(word))
    .map((word) => word[0].toUpperCase());
  return (letters.length > 1 ? letters[0] + letters[1] : (letters[0] ?? 'B') + 'K').slice(0, 2);
}

function parseServices(text) {
  const list = String(text || '')
    .split(',')
    .map((entry) => entry.trim())
    .filter(Boolean)
    .map((entry) => {
      const [name, duration, price] = entry.split(':').map((part) => part.trim());
      return {
        id: slugify(name),
        name,
        aliases: [name.toLowerCase()],
        durationMinutes: Number(duration) > 0 ? Number(duration) : 30,
        price: Number(price) >= 0 ? Number(price) : 0,
        description: `${name} appointment.`,
        intakeFields: [],
        confirmationNote: 'Please arrive a few minutes before your appointment.'
      };
    });
  if (!list.length) {
    list.push({
      id: 'appointment',
      name: 'Appointment',
      aliases: ['appointment', 'booking'],
      durationMinutes: 30,
      price: 0,
      description: 'Standard appointment.',
      intakeFields: [],
      confirmationNote: 'Please arrive a few minutes before your appointment.'
    });
  }
  return list;
}

function buildEnv(values) {
  const lines = [
    '# Generated by `npm run setup`. Keep this file private (it is gitignored).',
    '',
    '# --- Staff dashboard sign-in ---',
    `STAFF_USER=${values.staffUser}`,
    `STAFF_PASSWORD=${values.staffPassword}`,
    'SESSION_SECRET=' + crypto.randomBytes(32).toString('hex'),
    'API_KEY=' + crypto.randomBytes(24).toString('hex'),
    '',
    '# --- AI assistant ---',
    'AI_PROVIDER=' + (values.aiKey ? values.aiProvider : ''),
    values.aiProvider === 'openai' ? `OPENAI_API_KEY=${values.aiKey}` : 'OPENAI_API_KEY=',
    values.aiProvider === 'anthropic' ? `ANTHROPIC_API_KEY=${values.aiKey}` : 'ANTHROPIC_API_KEY=',
    values.aiProvider === 'gemini' ? `GEMINI_API_KEY=${values.aiKey}` : 'GEMINI_API_KEY=',
    'AI_TIMEOUT_MS=20000',
    '',
    '# --- Email (Resend) / SMS (Twilio) ---',
    `RESEND_API_KEY=${values.resendKey}`,
    `EMAIL_FROM=${values.emailFrom}`,
    `TWILIO_ACCOUNT_SID=${values.twilioSid}`,
    `TWILIO_AUTH_TOKEN=${values.twilioToken}`,
    `TWILIO_FROM=${values.twilioFrom}`,
    'NOTIFICATIONS_MODE=auto',
    '',
    '# --- Existing client system + website embed ---',
    `BRIDGE_WEBHOOK_URL=${values.bridgeUrl}`,
    'BRIDGE_WEBHOOK_TOKEN=',
    'RECONCILE_URL=',
    `EMBED_ORIGINS=${values.embedOrigins}`,
    '',
    '# --- Server ---',
    'PORT=3000',
    'HOST=127.0.0.1',
    'DATABASE_PATH=data/booking.db',
    ''
  ];
  return lines.join('\n');
}

const defaults = {
  name: flags.get('name') || 'My Business',
  industry: flags.get('industry') || 'services',
  timezone: flags.get('timezone') || Intl.DateTimeFormat().resolvedOptions().timeZone || 'UTC',
  locale: Intl.DateTimeFormat().resolvedOptions().locale || 'en-GB',
  currency: flags.get('currency') || 'GBP',
  location: flags.get('location') || '',
  phone: flags.get('phone') || '',
  email: flags.get('email') || 'hello@example.com',
  services: flags.get('services') || 'Appointment:30:0'
};

if (fs.existsSync(configPath) && !flags.has('force')) {
  console.error(`[setup] ${path.relative(process.cwd(), configPath)} already exists.`);
  console.error('[setup] Re-run with --force to replace it, or delete it first.');
  process.exit(1);
}

console.log('\nAppointment booking - first-run setup');
console.log('Press Enter to accept the value in brackets.\n');

const name = String(await ask('Business name', defaults.name));
const industry = String(await ask('Industry (dental, salon, clinic, gym, services)', defaults.industry));
const timezone = String(await ask('Timezone (IANA name)', defaults.timezone));
const currency = String(await ask('Currency code', defaults.currency));
const location = String(await ask('Address customers should see', defaults.location));
const phone = String(await ask('Phone number', defaults.phone));
const email = String(await ask('Public email address', defaults.email));
const servicesText = String(
  await ask('Services as Name:minutes:price, comma separated', defaults.services)
);
const staffUser = String(await ask('Staff username', flags.get('staff-user') || 'staff'));
const staffPassword = String(await ask('Staff password (leave blank to generate one)', flags.get('staff-password') || ''));
const aiProvider = String(await ask('AI provider (openai, anthropic, gemini, none)', flags.get('ai-provider') || 'none'));
const aiKey = String(await ask('AI API key (optional, can be added to .env later)', flags.get('ai-key') || ''));
const resendKey = String(await ask('Resend API key (optional)', flags.get('resend-key') || ''));
const emailFrom = String(await ask('From address for email', flags.get('email-from') || `${name} <${email}>`));
const twilioSid = String(await ask('Twilio account SID (optional)', flags.get('twilio-sid') || ''));
const twilioToken = String(await ask('Twilio auth token (optional)', flags.get('twilio-token') || ''));
const twilioFrom = String(await ask('Twilio sender number, E.164 (optional)', flags.get('twilio-from') || ''));
const bridgeUrl = String(await ask('Existing system webhook URL (optional)', flags.get('bridge-url') || ''));
const embedOrigins = String(await ask('Website origins allowed to embed the widget (optional)', flags.get('embed-origins') || ''));
rl?.close();

const generatedPassword = !staffPassword;
const password = staffPassword || crypto.randomBytes(9).toString('base64url');
const referencePrefix = initials(name);

const config = {
  business: {
    id: slugify(name),
    name,
    referencePrefix,
    industry,
    timezone,
    locale: defaults.locale,
    currency,
    location,
    directions: '',
    bookingInstructions: 'Please arrive a few minutes before your appointment. Call us if you need to change it.',
    supportPhone: phone,
    supportEmail: email,
    outOfScopeMessage:
      'I can help with booking, changing or cancelling appointments. Anything else is best handled by our team, and I have passed your message on to them.',
    escalationKeywords: [],
    escalationMessage: '',
    conversation: {
      greeting: `Thanks for getting in touch with ${name}. I can check availability and get you booked in. What do you need help with?`,
      askForName: 'Happy to help. What is your full name?',
      askForEmail: 'Thanks. What is the best email address to send your confirmation to?',
      askForPhone: 'And the best phone number in case we need to reach you on the day?',
      askForService: 'Which service can I book for you?',
      askForTime:
        "What day and time would suit you? For example: 'Tuesday at 2pm' or 'next Friday morning'."
    }
  },
  calendar: {
    slotIntervalMinutes: 15,
    bufferBeforeMinutes: 0,
    bufferAfterMinutes: 10,
    minNoticeMinutes: 120,
    maxAdvanceDays: 60,
    workingHours: {
      mon: [['09:00', '17:00']],
      tue: [['09:00', '17:00']],
      wed: [['09:00', '17:00']],
      thu: [['09:00', '17:00']],
      fri: [['09:00', '16:00']],
      sat: [],
      sun: []
    },
    blackoutDates: []
  },
  services: parseServices(servicesText),
  reminders: [
    { id: '24h', label: '24-hour reminder', minutesBefore: 1440, channel: 'email', template: 'reminder-24h' },
    { id: '1h', label: '1-hour reminder', minutesBefore: 60, channel: 'sms', template: 'reminder-1h' }
  ],
  notifications: {
    mode: 'auto',
    fromEmail: emailFrom,
    fromPhone: name,
    webhookUrl: '',
    webhookToken: '',
    smsFrom: twilioFrom
  },
  policies: {
    cancellationNoticeHours: 24,
    maxActiveBookingsPerCustomer: 3,
    duplicateWindowMinutes: 1440
  },
  integrations: {
    webhook: { url: bridgeUrl, token: '', events: ['created', 'rescheduled', 'cancelled'] }
  }
};

fs.mkdirSync(path.dirname(configPath), { recursive: true });
fs.writeFileSync(configPath, `${JSON.stringify(config, null, 2)}\n`);

if (fs.existsSync(envPath)) {
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  fs.copyFileSync(envPath, `${envPath}.backup-${stamp}`);
  console.log(`[setup] existing .env copied to .env.backup-${stamp}`);
}

const envValues = {
  staffUser,
  staffPassword: password,
  aiProvider: ['openai', 'anthropic', 'gemini'].includes(aiProvider.toLowerCase()) ? aiProvider.toLowerCase() : 'gemini',
  aiKey,
  resendKey,
  emailFrom,
  twilioSid,
  twilioToken,
  twilioFrom,
  bridgeUrl,
  embedOrigins
};
fs.writeFileSync(envPath, buildEnv(envValues), { mode: 0o600 });

console.log('\nCreated:');
console.log(`  ${path.relative(process.cwd(), configPath)}`);
console.log(`  ${path.relative(process.cwd(), envPath)}`);
console.log(`\n  Services: ${config.services.map((service) => `${service.name} (${service.durationMinutes} min)`).join(', ')}`);
console.log(`  Hours:    Mon-Fri, ${config.calendar.workingHours.mon[0][0]}-${config.calendar.workingHours.fri[0][1]}`);
if (generatedPassword) {
  console.log(`\n  Staff login: ${staffUser} / ${password}`);
  console.log('  This password is only printed once - it is also in .env.');
}
console.log('\nNext:');
console.log('  npm start                 # http://localhost:3000  (staff: /admin)');
console.log('  npm test                  # verify the workflow');
console.log('  npm run backup            # nightly snapshot once live');
console.log('  deploy: see "Deploying it" in README.md\n');
